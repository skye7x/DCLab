#!/usr/bin/env python3
"""Generate device pictogram assets from tools/pictograms.json.

Outputs
  scenes/devices/pictogram_shapes.gd        (Godot data, used by DevicePictograms)
  dclab-web/components/pictogramShapes.js   (web data, used by Pictogram.jsx)
  tools/pictograms_preview.svg              (contact sheet for quick review)
"""
import json, pathlib, math

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = json.loads((ROOT / "tools" / "pictograms.json").read_text())
SHAPES = {k: v for k, v in SRC.items() if not k.startswith("_")}


def n(x):  # compact number
    return ("%g" % x)


def gd_value(op):
    parts = [f'"t": "{op["t"]}"']
    for k, v in op.items():
        if k == "t":
            continue
        if isinstance(v, list):
            if k == "p":
                parts.append(f'"p": [{", ".join(n(i) for i in v)}]')
            else:
                parts.append(f'"{k}": Vector2({n(v[0])}, {n(v[1])})')
        else:
            parts.append(f'"{k}": {float(v)!r}')
    return "{" + ", ".join(parts) + "}"


def write_gd():
    out = [
        "class_name PictogramShapes",
        "extends RefCounted",
        "",
        "## GENERATED by tools/gen_pictograms.py from tools/pictograms.json. Do not edit by hand.",
        "## 24x24 grid, drawn by DevicePictograms.",
        "",
        "const SHAPES := {",
    ]
    for name, ops in SHAPES.items():
        out.append(f'\t"{name}": [')
        out += [f"\t\t{gd_value(o)}," for o in ops]
        out.append("\t],")
    out.append("}")
    (ROOT / "scenes/devices/pictogram_shapes.gd").write_text("\n".join(out) + "\n")


def write_js():
    body = json.dumps(SHAPES, separators=(",", ":"))
    (ROOT / "dclab-web/components/pictogramShapes.js").write_text(
        "// GENERATED by tools/gen_pictograms.py from tools/pictograms.json. Do not edit by hand.\n"
        f"export const SHAPES = {body};\n"
    )


def svg_op(op):
    t = op["t"]
    if t == "rrect":
        return f'<rect x="{n(op["x"])}" y="{n(op["y"])}" width="{n(op["w"])}" height="{n(op["h"])}" rx="{n(op["r"])}" class="s f"/>'
    if t == "frect":
        return f'<rect x="{n(op["x"])}" y="{n(op["y"])}" width="{n(op["w"])}" height="{n(op["h"])}" class="f"/>'
    if t == "circle":
        return f'<circle cx="{n(op["c"][0])}" cy="{n(op["c"][1])}" r="{n(op["r"])}" class="s f"/>'
    if t == "ellipse":
        return f'<ellipse cx="{n(op["c"][0])}" cy="{n(op["c"][1])}" rx="{n(op["rx"])}" ry="{n(op["ry"])}" class="s f"/>'
    if t == "arc":
        cx, cy = op["c"]; rx, ry = op["rx"], op["ry"]
        return f'<path d="M{n(cx-rx)} {n(cy)}A{n(rx)} {n(ry)} 0 0 0 {n(cx+rx)} {n(cy)}" class="s"/>'
    if t == "line":
        a = op["p"]
        return f'<path d="M{n(a[0])} {n(a[1])}L{n(a[2])} {n(a[3])}" class="s"/>'
    if t == "poly":
        a = op["p"]
        pts = " ".join(f"{n(a[i])} {n(a[i+1])}" for i in range(0, len(a), 2))
        return f'<path d="M{pts.replace(" ", " ", 1)}" class="s" data-poly="1"/>'
    if t == "dot":
        return f'<circle cx="{n(op["c"][0])}" cy="{n(op["c"][1])}" r="{n(op["r"])}" class="dot"/>'
    raise ValueError(t)


def svg_poly_fix(s):
    # Build proper "M x y L x y L ..." for polylines
    return s


def svg_group(ops):
    res = []
    for op in ops:
        if op["t"] == "poly":
            a = op["p"]
            d = "M" + "L".join(f"{n(a[i])} {n(a[i+1])}" for i in range(0, len(a), 2))
            res.append(f'<path d="{d}" class="s"/>')
        else:
            res.append(svg_op(op))
    return "".join(res)


def write_preview():
    cell = 120
    names = [k for k in SHAPES if k != "generic"]
    w = cell * len(names)
    css = (
        "<style>.s{fill:none;stroke:#ededed;stroke-width:1.5;stroke-linecap:round;stroke-linejoin:round}"
        ".f{fill:rgba(0,112,243,.16)}.dot{fill:#3291ff}"
        "text{font:500 10px ui-monospace,monospace;fill:#8f8f8f;text-anchor:middle}</style>"
    )
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{cell+40}" viewBox="0 0 {w} {cell+40}">{css}'
             f'<rect width="100%" height="100%" fill="#0a0a0a"/>']
    for i, name in enumerate(names):
        x = i * cell + (cell - 72) / 2
        parts.append(f'<g transform="translate({x} 12) scale(3)">{svg_group(SHAPES[name])}</g>')
        parts.append(f'<text x="{i*cell+cell/2}" y="{cell+20}">{name}</text>')
    parts.append("</svg>")
    (ROOT / "tools/pictograms_preview.svg").write_text("".join(parts))


if __name__ == "__main__":
    write_gd(); write_js(); write_preview()
    print("generated", len(SHAPES), "pictograms")
